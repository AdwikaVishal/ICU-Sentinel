# ruff: noqa: E402
"""Generate P2 advanced tabular ML artifacts from P1 processed data.

This script requires P1 artifacts (preprocessed patients, splits, and features)
to exist. It trains Extra Trees, LightGBM, and XGBoost models on the P1
feature contract, selects thresholds on validation, and evaluates once on test.

Expected inputs (generated by scripts/generate_p1_artifacts.py):
    data/features/patients/*.parquet    (per-patient engineered features)
    data/splits/split_manifest.json     (patient-level train/val/test)
    data/features/feature_schema.json   (feature contract)

Usage:
    python scripts/generate_p2_artifacts.py
    python scripts/generate_p2_artifacts.py --disable-lightgbm  # skip problematic model
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from ml.p2_boosting.config import P2Config, safe_thread_default
from ml.p2_boosting.training import train_p2_from_artifacts


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--processed-dir",
        type=Path,
        default=_REPO_ROOT / "data" / "features" / "patients",
    )
    parser.add_argument(
        "--split-manifest",
        type=Path,
        default=_REPO_ROOT / "data" / "splits" / "split_manifest.json",
    )
    parser.add_argument(
        "--feature-schema",
        type=Path,
        default=_REPO_ROOT / "data" / "features" / "feature_schema.json",
    )
    parser.add_argument(
        "--artifact-dir", type=Path, default=_REPO_ROOT / "artifacts" / "p2"
    )
    parser.add_argument(
        "--reports-dir",
        type=Path,
        default=_REPO_ROOT / "data" / "reports" / "p2",
    )
    parser.add_argument(
        "--disable-lightgbm",
        action="store_true",
        help="Skip LightGBM (useful if DLL issues exist).",
    )
    parser.add_argument(
        "--extra-trees-estimators",
        type=int,
        default=200,
        help="Number of Extra Trees estimators.",
    )
    parser.add_argument(
        "--extra-trees-depth",
        type=int,
        default=None,
        help="Maximum Extra Trees depth (default: unlimited).",
    )
    parser.add_argument(
        "--xgboost-estimators",
        type=int,
        default=200,
        help="Number of XGBoost boosting rounds.",
    )
    parser.add_argument(
        "--xgboost-depth",
        type=int,
        default=4,
        help="Maximum XGBoost tree depth.",
    )
    parser.add_argument(
        "--extra-trees-n-jobs",
        type=int,
        default=safe_thread_default(),
        help="Parallel jobs for Extra Trees. Default is a safe value that "
        "leaves CPU headroom for Windows.",
    )
    parser.add_argument(
        "--xgboost-n-jobs",
        type=int,
        default=safe_thread_default(),
        help="Parallel jobs for XGBoost. Default is a safe value that "
        "leaves CPU headroom for Windows.",
    )
    parser.add_argument(
        "--source",
        type=str,
        default="real",
        help="Data source label (real/synthetic).",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing P2 artifacts/reports.",
    )
    parser.add_argument(
        "--train-patients",
        type=int,
        default=8000,
        help="Patient-level train subsample (0=full). Reuses split_manifest_fast.json if present.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for train subsample.",
    )
    return parser.parse_args()


def main() -> int:
    args = _parse_args()

    if not args.processed_dir.is_dir():
        print(
            f"ERROR: processed patient features not found at {args.processed_dir}.\n"
            f"Run scripts/generate_p1_artifacts.py first to generate P1 data.",
            file=sys.stderr,
        )
        return 2

    if not args.split_manifest.exists():
        print(
            f"ERROR: split manifest not found at {args.split_manifest}.\n"
            f"Run scripts/generate_p1_artifacts.py first.",
            file=sys.stderr,
        )
        return 2

    # Use fast manifest (patient-level subsample) to avoid OOM on full 1.55M rows.
    if args.train_patients > 0:
        fast_manifest = args.split_manifest.parent / "split_manifest_fast.json"
        if not fast_manifest.exists():
            import json as _json
            from sklearn.model_selection import train_test_split as _tts
            with open(args.split_manifest) as _f:
                _m = _json.load(_f)
            _train = [p for p in _m["patients"] if p["split"] == "train"]
            _other = [p for p in _m["patients"] if p["split"] != "train"]
            if args.train_patients < len(_train):
                _labels = [bool(p["has_sepsis"]) for p in _train]
                _sel, _ = _tts(_train, train_size=args.train_patients,
                               random_state=args.seed, stratify=_labels)
            else:
                _sel = _train
            _m["patients"] = sorted(_sel + _other, key=lambda p: p["patient_id"])
            fast_manifest.parent.mkdir(parents=True, exist_ok=True)
            with open(fast_manifest, "w") as _f:
                _json.dump(_m, _f, indent=2)
            print(f"Created fast manifest: {len(_sel)} train patients -> {fast_manifest}")
        else:
            print(f"Reusing existing fast manifest: {fast_manifest}")
        args.split_manifest = fast_manifest

    config = P2Config(
        train_extra_trees=True,
        train_lightgbm=not args.disable_lightgbm,
        train_xgboost=True,
    )
    config.extra_trees.n_estimators = args.extra_trees_estimators
    config.extra_trees.max_depth = args.extra_trees_depth
    config.extra_trees.n_jobs = args.extra_trees_n_jobs
    config.xgboost.n_estimators = args.xgboost_estimators
    config.xgboost.max_depth = args.xgboost_depth
    config.xgboost.n_jobs = args.xgboost_n_jobs

    if args.disable_lightgbm:
        print("WARNING: LightGBM disabled by user request.")

    print(f"Loading P1 artifacts from {args.processed_dir}")
    print(f"Split manifest: {args.split_manifest}")
    print(f"Enabled models: {config.enabled_models()}")

    result = train_p2_from_artifacts(
        processed_dir=args.processed_dir,
        split_manifest_path=args.split_manifest,
        feature_schema_path=args.feature_schema if args.feature_schema.exists() else None,
        config=config,
        artifact_dir=args.artifact_dir,
        reports_dir=args.reports_dir,
        source=args.source,
        overwrite=args.overwrite,
    )

    print("\nP2 Training Complete:")
    print(f"  Models trained: {list(result.models.keys())}")
    print(f"  Features used: {result.n_features_total} features")
    print(f"  Target: {result.target_column}")
    print(f"  Split check: {result.split_check.get('leakage_detected', 'unknown')}")
    print("\nValidation thresholds (selected on validation split):")
    for name, threshold in result.thresholds.items():
        print(f"  {name}: {threshold:.3f}")
    print("\nValidation metrics:")
    for name, metrics in result.validation_metrics.items():
        m = metrics.get("metrics", {})
        print(
            f"  {name}: AUROC={m.get('auroc', float('nan')):.3f}, "
            f"AUPRC={m.get('auprc', float('nan')):.3f}, "
            f"F1={m.get('f1', float('nan')):.3f}"
        )
    if result.test_metrics:
        print("\nTest metrics (one-shot evaluation at validation threshold):")
        for name, metrics in result.test_metrics.items():
            m = metrics.get("metrics", {})
            print(
                f"  {name}: AUROC={m.get('auroc', float('nan')):.3f}, "
                f"AUPRC={m.get('auprc', float('nan')):.3f}, "
                f"F1={m.get('f1', float('nan')):.3f}"
            )

    print(f"\nArtifacts saved to: {args.artifact_dir}")
    print(f"Reports saved to: {args.reports_dir}")
    print("  - p2_thresholds.json")
    print("  - p2_training_summary.json")
    print("  - p2_experiment.json")

    if args.source == "synthetic":
        print(
            "\n⚠️  WARNING: These results use synthetic fixture data for "
            "software validation only.\n   They are NOT scientific evidence "
            "and must not be reported as real performance."
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
