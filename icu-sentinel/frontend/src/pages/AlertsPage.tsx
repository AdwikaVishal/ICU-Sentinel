import { BellRing, Info, RefreshCw, ShieldAlert } from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import { useSearchParams } from "react-router-dom";

import type { AlertRecord, AlertStatus } from "../api/types";
import { AlertDetails } from "../components/alerts/AlertDetails";
import { AlertSummary } from "../components/alerts/AlertSummary";
import { AlertTable } from "../components/alerts/AlertTable";
import { PageHeader } from "../components/common/PageHeader";
import { SectionCard } from "../components/common/SectionCard";
import {
  ErrorState,
  LoadingState,
} from "../components/common/StateViews";
import { useAlertCentre } from "../hooks/useExplanation";

const FILTERS: Array<{ key: "ALL" | AlertStatus; label: string }> = [
  { key: "ALL", label: "All" },
  { key: "ACTIVE", label: "Active" },
  { key: "ACKNOWLEDGED", label: "Acknowledged" },
  { key: "CLEARED", label: "Cleared" },
];

export function AlertsPage() {
  const centre = useAlertCentre();
  const [searchParams, setSearchParams] = useSearchParams();
  const requestedStatus = searchParams.get("status");
  const initialFilter: "ALL" | AlertStatus =
    requestedStatus === "ACTIVE" ||
    requestedStatus === "ACKNOWLEDGED" ||
    requestedStatus === "CLEARED"
      ? requestedStatus
      : "ALL";

  const [filter, setFilter] = useState<"ALL" | AlertStatus>(initialFilter);
  const [query, setQuery] = useState("");
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);

  const alerts: AlertRecord[] = useMemo(() => {
    if (centre.all) return centre.all.alerts;
    return [...(centre.active?.alerts ?? []), ...(centre.history?.alerts ?? [])];
  }, [centre.active, centre.all, centre.history]);

  const filtered = useMemo(() => {
    const term = query.trim().toLowerCase();
    return alerts.filter((alert) => {
      const statusMatch = filter === "ALL" || alert.status === filter;
      const queryMatch =
        !term ||
        alert.patient_id.toLowerCase().includes(term) ||
        alert.alert_id.toLowerCase().includes(term);
      return statusMatch && queryMatch;
    });
  }, [alerts, filter, query]);

  useEffect(() => {
    if (filtered.length === 0) {
      setSelectedId(null);
      return;
    }
    if (!selectedId || !filtered.some((alert) => alert.alert_id === selectedId)) {
      setSelectedId(filtered[0].alert_id);
    }
  }, [filtered, selectedId]);

  const selected =
    alerts.find((alert) => alert.alert_id === selectedId) ?? null;

  const countsAvailable = !centre.loading && !centre.error && centre.all !== null;
  const countByStatus = (status: AlertStatus) =>
    countsAvailable
      ? alerts.filter((alert) => alert.status === status).length
      : null;

  const handleFilter = (next: "ALL" | AlertStatus) => {
    setFilter(next);
    const params = new URLSearchParams(searchParams);
    if (next === "ALL") params.delete("status");
    else params.set("status", next);
    setSearchParams(params, { replace: true });
  };

  const handleAcknowledge = async (alertId: string) => {
    setNotice(null);
    const ok = await centre.acknowledge(alertId);
    if (ok) setNotice(`Alert ${alertId} acknowledged.`);
  };

  const handleClear = async (alertId: string) => {
    setNotice(null);
    const ok = await centre.clear(alertId, "manual_clear_from_alert_centre");
    if (ok) setNotice(`Alert ${alertId} cleared.`);
  };

  return (
    <div className="page">
      <PageHeader
        eyebrow={
          <>
            <BellRing size={12} aria-hidden="true" />
            Clinical workflow
          </>
        }
        title="Sepsis Risk Alerts"
        description="Monitor, review, and manage risk alert episodes generated by the configured demonstration threshold."
        actions={
          <button
            type="button"
            className="btn btn--secondary"
            onClick={centre.reload}
            disabled={centre.loading}
          >
            <RefreshCw size={15} aria-hidden="true" />
            Refresh alerts
          </button>
        }
      />

      {centre.loading ? <LoadingState label="Loading alert episodes…" /> : null}
      {centre.error ? (
        <ErrorState error={centre.error} onRetry={centre.reload} />
      ) : null}

      <AlertSummary
        active={countByStatus("ACTIVE")}
        acknowledged={countByStatus("ACKNOWLEDGED")}
        cleared={countByStatus("CLEARED")}
        total={countsAvailable ? alerts.length : null}
      />

      <div className="disclaimer" role="note">
        <ShieldAlert size={15} aria-hidden="true" />
        <span>
          <strong>Research workflow only.</strong> Alerts are generated by a
          configurable demonstration threshold and are not clinically validated.
          They must not be used as the sole basis for clinical decisions.
        </span>
      </div>

      {centre.actionError ? (
        <p className="inline-error" role="alert">
          Alert action failed: {centre.actionError}
        </p>
      ) : null}
      {notice ? (
        <p className="inline-success" role="status">
          {notice}
        </p>
      ) : null}

      {!centre.loading && !centre.error ? (
        <>
          <div className="alerts-layout">
            <SectionCard
              title={`Alert episodes${centre.all ? ` (${filtered.length})` : ""}`}
              description="One ongoing episode per patient and rule. Later scores inside the deduplication window update the episode instead of creating duplicates."
            >
              <div className="alert-toolbar">
                <div className="filter-pills" role="group" aria-label="Alert status filter">
                  {FILTERS.map((item) => (
                    <button
                      key={item.key}
                      type="button"
                      className={`filter-pill${filter === item.key ? " is-active" : ""}`}
                      onClick={() => handleFilter(item.key)}
                      aria-pressed={filter === item.key}
                    >
                      {item.label}
                      {item.key === "ALL"
                        ? ` · ${alerts.length}`
                        : ` · ${alerts.filter((alert) => alert.status === item.key).length}`}
                    </button>
                  ))}
                </div>
                <div className="alert-toolbar__search">
                  <label className="field" style={{ minWidth: 0 }}>
                    <span className="field__label">Patient search</span>
                    <input
                      type="search"
                      className="input input--search"
                      value={query}
                      onChange={(event) => setQuery(event.target.value)}
                      placeholder="Patient ID or alert ID"
                      aria-label="Search alerts by patient or alert ID"
                    />
                  </label>
                </div>
              </div>

              <AlertTable
                alerts={filtered}
                selectedId={selectedId}
                busyId={centre.actionId}
                onSelect={(alert) => setSelectedId(alert.alert_id)}
                onAcknowledge={handleAcknowledge}
                onClear={handleClear}
              />
            </SectionCard>

            <AlertDetails
              alert={selected}
              threshold={centre.threshold}
              busy={selected !== null && centre.actionId === selected.alert_id}
              onAcknowledge={handleAcknowledge}
              onClear={handleClear}
            />
          </div>

          <div className="grid grid--2">
            <SectionCard
              title="Threshold configuration"
              description="Configured demonstration rule. Threshold selection never uses the ground-truth label."
            >
              {centre.threshold ? (
                <div className="summary-grid">
                  <div className="summary-tile">
                    <dt>Threshold</dt>
                    <dd className="numeric">
                      {centre.threshold.threshold.toFixed(2)}
                    </dd>
                  </div>
                  <div className="summary-tile">
                    <dt>Rule</dt>
                    <dd>{centre.threshold.rule_id}</dd>
                  </div>
                  <div className="summary-tile">
                    <dt>Source</dt>
                    <dd>
                      {centre.threshold.source} · {centre.threshold.version}
                    </dd>
                  </div>
                  <div className="summary-tile">
                    <dt>Deduplication</dt>
                    <dd>{centre.threshold.dedup_window_hours} h window</dd>
                  </div>
                  <div className="summary-tile">
                    <dt>Clear below threshold</dt>
                    <dd>
                      {centre.threshold.clear_on_below_threshold
                        ? "Enabled"
                        : "Disabled"}
                    </dd>
                  </div>
                  <div className="summary-tile">
                    <dt>Clinical validation</dt>
                    <dd>
                      <span className="badge badge--warn">
                        {centre.threshold.clinically_validated
                          ? "Validated"
                          : "Not clinically validated"}
                      </span>
                    </dd>
                  </div>
                </div>
              ) : (
                <p className="muted small">
                  The alert threshold is not available from the configured alert
                  engine.
                </p>
              )}
              {centre.threshold ? (
                <p className="muted tiny" style={{ marginTop: 12 }}>
                  {centre.threshold.disclosure}
                </p>
              ) : null}
            </SectionCard>

            <SectionCard
              title="How this workflow behaves"
              description="Lifecycle and deduplication rules for the demonstration."
            >
              <ul className="notes">
                <li>
                  <strong>ACTIVE</strong> — the configured threshold was reached
                  and the episode has not been reviewed or cleared.
                </li>
                <li>
                  <strong>ACKNOWLEDGED</strong> — a reviewer has seen the episode.
                  It leaves the active queue but is not deleted.
                </li>
                <li>
                  <strong>CLEARED</strong> — the episode was cleared manually or
                  because the score fell below the configured threshold.
                </li>
                <li>
                  An episode is updated rather than duplicated while the next
                  score is inside the deduplication window. Navigating backwards in
                  replay never creates another episode.
                </li>
              </ul>
              <p className="chart-footnote">
                <Info size={13} aria-hidden="true" />
                An empty alert queue is not evidence that a patient is stable.
              </p>
            </SectionCard>
          </div>
        </>
      ) : null}
    </div>
  );
}
